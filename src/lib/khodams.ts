export function getKhodamById(id: number): Khodam | undefined {
  return KHODAMS.find(k => k.id === id);
}

export function generateDeterministicKhodamId(name: string): number {
  const normalizedName = name.trim().toLowerCase();
  let hash = 0;
  for (let i = 0; i < normalizedName.length; i++) {
    const char = normalizedName.charCodeAt(i);
    hash = ((hash << 5) - hash) + char;
    hash |= 0; // Convert to 32bit integer
  }
  
  const index = Math.abs(hash) % KHODAMS.length;
  return KHODAMS[index].id;
}
